// Preview page behavior. Every feature here is an enhancement:
// without JavaScript the quote answer is a <details>, receipts stay off,
// and the grease-pencil circles are drawn statically.
document.documentElement.classList.remove('no-js');
document.documentElement.classList.add('js');

// ---------- Receipts toggle ----------
(function () {
  const btn = document.querySelector('.receipts-toggle');
  if (!btn) return;
  const set = on => {
    document.body.classList.toggle('receipts-on', on);
    btn.setAttribute('aria-pressed', String(on));
    btn.lastChild.textContent = on ? 'Hide how this was made' : 'Show how this was made';
    try { localStorage.setItem('receipts', on ? '1' : '0'); } catch (e) {}
  };
  let saved = false;
  try { saved = localStorage.getItem('receipts') === '1'; } catch (e) {}
  set(saved);
  btn.addEventListener('click', () => set(btn.getAttribute('aria-pressed') !== 'true'));
})();

// ---------- Quote test ----------
(function () {
  const choices = document.querySelectorAll('.quote-choice');
  const answer = document.querySelector('.answer');
  if (!choices.length || !answer) return;
  choices.forEach(btn => btn.addEventListener('click', () => {
    choices.forEach(c => {
      c.disabled = true;
      c.dataset.state = c.dataset.real === 'true' ? 'real' : 'made';
      c.querySelector('.verdict').textContent = c.dataset.real === 'true' ? 'A person said this' : 'Generated by AI';
      c.setAttribute('aria-pressed', String(c === btn));
    });
    const right = btn.dataset.real === 'true';
    answer.querySelector('[data-result]').textContent = right
      ? 'You picked the real one.'
      : 'You picked the generated one. Most people do.';
    answer.open = true;
    answer.querySelector('[data-result]').focus();
  }));
})();

// ---------- Grease pencil circles draw in when seen ----------
(function () {
  const marks = document.querySelectorAll('.grease');
  if (!marks.length) return;
  if (!('IntersectionObserver' in window) || matchMedia('(prefers-reduced-motion: reduce)').matches) {
    marks.forEach(m => m.classList.add('drawn')); return;
  }
  const io = new IntersectionObserver(entries => entries.forEach(e => {
    if (e.isIntersecting) { e.target.classList.add('drawn'); io.unobserve(e.target); }
  }), { threshold: 0.6 });
  marks.forEach(m => io.observe(m));
})();
