// ramidaud.com · E1 behavior. Every feature is an enhancement: without this
// script the page is complete, readable and navigable.
(function () {
  const root = document.documentElement;
  root.classList.add('js');
  const page = document.querySelector('.page');
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const store = {
    get(k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
    set(k, v) { try { localStorage.setItem(k, v); } catch (e) {} }
  };

  // ---------- Provenance: flip every card ----------
  const provBtns = document.querySelectorAll('[data-prov-toggle]');
  function setProv(on) {
    page && page.classList.toggle('prov-on', on);
    provBtns.forEach(b => {
      b.setAttribute('aria-pressed', String(on));
      b.textContent = on ? '[ Hide provenance ]' : '[ Show provenance ]';
    });
    store.set('prov', on ? '1' : '0');
  }
  provBtns.forEach(b => b.addEventListener('click', () => setProv(b.getAttribute('aria-pressed') !== 'true')));
  if (provBtns.length) setProv(store.get('prov') === '1');

  // ---------- Phone menu ----------
  const menuBtn = document.querySelector('.menu-btn');
  if (menuBtn && page) {
    menuBtn.addEventListener('click', () => {
      const open = menuBtn.getAttribute('aria-expanded') !== 'true';
      menuBtn.setAttribute('aria-expanded', String(open));
      menuBtn.textContent = open ? 'Close' : 'Menu';
      page.classList.toggle('menu-open', open);
    });
    document.addEventListener('keydown', e => {
      if (e.key === 'Escape' && page.classList.contains('menu-open')) { menuBtn.click(); menuBtn.focus(); }
    });
  }

  // ---------- Typed headline ----------
  const head = document.querySelector('[data-typed]');
  const sub = document.querySelector('.subhead');
  const flag = document.querySelector('.typing-flag');
  if (head && !reduce) {
    const ghost = head.querySelector('.typed-ghost');
    const live = head.querySelector('.typed-live');
    // Segments keep the italic run styled while it types.
    const segs = [...ghost.childNodes].map(n => ({ text: n.textContent, italic: n.nodeName === 'I' }));
    const total = segs.reduce((t, s) => t + s.text.length, 0);
    const caret = document.createElement('span'); caret.className = 'caret';
    head.classList.add('typing');
    if (sub) sub.classList.add('pending');
    let n = 0;
    const render = () => {
      live.textContent = '';
      let left = n;
      segs.forEach(s => {
        if (left <= 0) return;
        const part = s.text.slice(0, left); left -= part.length;
        if (s.italic) { const i = document.createElement('i'); i.textContent = part; live.appendChild(i); }
        else live.appendChild(document.createTextNode(part));
      });
      live.appendChild(caret);
    };
    const all = segs.map(s => s.text).join('');
    const step = () => {
      if (n >= total) {
        head.classList.remove('typing');
        flag && flag.classList.remove('on');
        if (sub) sub.classList.remove('pending');
        setTimeout(() => caret.classList.add('off'), 2600);
        return;
      }
      n++; render();
      if (n === 1 && flag) flag.classList.add('on');
      const ch = all[n - 1];
      setTimeout(step, ch === '.' ? 260 : ch === ' ' ? 70 : 34 + Math.round(Math.random() * 40));
    };
    render();
    setTimeout(step, 900);
  }

  // ---------- Hero spotlight (fine pointers only) ----------
  const hero = document.querySelector('.hero');
  if (hero && window.matchMedia('(hover: hover) and (pointer: fine)').matches && !reduce) {
    hero.addEventListener('pointermove', e => {
      const r = hero.getBoundingClientRect();
      hero.style.setProperty('--mx', Math.round(e.clientX - r.left) + 'px');
      hero.style.setProperty('--my', Math.round(e.clientY - r.top) + 'px');
    });
  }

  // ---------- Quote test ----------
  const qbtns = document.querySelectorAll('.qbtn');
  const answer = document.querySelector('.answer');
  qbtns.forEach(btn => btn.addEventListener('click', () => {
    qbtns.forEach(b => {
      const real = b.dataset.real === 'true';
      b.dataset.state = real ? 'real' : 'made';
      b.disabled = true;
      b.querySelector('.qverdict').textContent = real ? ' · A person said this' : ' · Generated by AI';
      b.setAttribute('aria-pressed', String(b === btn));
    });
    if (answer) {
      answer.querySelector('[data-result]').textContent = btn.dataset.real === 'true'
        ? 'You picked the real one.' : 'You picked the generated one. Most people do.';
      answer.open = true;
    }
  }));

  // ---------- Latest writing from the shared index ----------
  const log = document.querySelector('[data-latest]');
  if (log) {
    const base = log.dataset.base || '';
    fetch(base + 'assets/data/writing.json').then(r => r.json()).then(d => {
      const items = d.items.filter(i => !i.draft).sort((a, b) => b.date.localeCompare(a.date)).slice(0, 3);
      log.innerHTML = '';
      items.forEach(i => {
        const li = document.createElement('li');
        const a = document.createElement('a');
        a.href = /^https?:/.test(i.url) ? i.url : base + i.url;
        const when = document.createElement('span'); when.className = 'when';
        when.textContent = i.date.replaceAll('-', ' ') + ' · ' + i.type;
        const what = document.createElement('span'); what.className = 'what'; what.textContent = i.title;
        a.append(when, what); li.appendChild(a); log.appendChild(li);
      });
    }).catch(() => {});
  }

  // ---------- Latest dispatch feature ----------
  const feat = document.querySelector('[data-latest-feature]');
  if (feat) {
    const base = feat.dataset.base || '';
    fetch(base + 'assets/data/writing.json').then(r => r.json()).then(d => {
      const list = d.items.map((x, k) => ({ ...x, _k: k })).filter(x => !x.draft);
      const i = list.sort((a, b) => b.date.localeCompare(a.date) || b._k - a._k)[0];
      if (!i) return;
      const thread = d.threads[i.thread] || {};
      const url = /^https?:/.test(i.url) ? i.url : base + i.url;
      feat.href = url;
      feat.querySelector('[data-kicker]').textContent = 'Latest dispatch · ' + i.date.replaceAll('-', ' ') + ' · ' + i.type;
      feat.querySelector('[data-title]').textContent = i.title;
      const dek = feat.querySelector('[data-dek]');
      dek.textContent = i.dek || thread.blurb || '';
      feat.querySelector('[data-venue]').textContent = i.venue;
      feat.querySelector('[data-thread]').textContent = thread.label || '';
      const art = feat.querySelector('[data-art]');
      const credit = feat.querySelector('[data-art-credit]');
      const img = i.image || thread.art;
      art.textContent = '';
      if (img) {
        art.className = 'feature-art art--image';
        const el = document.createElement('img');
        el.src = /^https?:/.test(img.src) ? img.src : base + img.src;
        el.alt = ''; el.loading = 'lazy';
        art.appendChild(el);
        credit.innerHTML = '<b>ART</b> ';
        credit.appendChild(document.createTextNode(img.credit || 'Image by Rami Daud.'));
      } else {
        const glyph = document.createElement('span'); glyph.className = 'art-glyph';
        const note = document.createElement('span'); note.className = 'art-note';
        if (i.thread === 'ai-practice') {
          art.className = 'feature-art art--quote'; glyph.textContent = '\u201C\u201D'; note.textContent = i.type;
        } else {
          art.className = 'feature-art art--type';
          const num = (i.tags || []).find(t => /^\d+$/.test(t));
          glyph.textContent = num ? num : (thread.label || i.title).slice(0, 2).toUpperCase();
          note.textContent = (i.type + (num ? ' ' + num : '')).toUpperCase();
        }
        art.append(glyph, note);
        credit.innerHTML = '<b>ART</b> Typeset for this card. No image used.';
      }
    }).catch(() => {});
  }

  // ---------- Footer year ----------
  document.querySelectorAll('[data-year]').forEach(el => { el.textContent = new Date().getFullYear(); });
})();
